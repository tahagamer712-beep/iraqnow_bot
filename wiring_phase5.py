def apply():
    """يطبق مرة واحدة بعد تحميل كل الوحدات."""
    applied, skipped = 0, 0
    missing = []
    for target_name, gname, src_name in WIRING:
        target = _sys.modules.get(target_name)
        src = _sys.modules.get(src_name)
        if target is None or src is None:
            missing.append((target_name, gname, src_name))
            continue
        if hasattr(target, gname):
            skipped += 1
            continue
        if not hasattr(src, gname):
            missing.append((target_name, gname, src_name))
            continue
        setattr(target, gname, getattr(src, gname))
        applied += 1
    _logger.info("wiring_phase5: ربط %d اسم (%d موجود، %d ناقص)", applied, skipped, len(missing))
    for m in missing[:20]:
        _logger.warning("wiring_phase5: تعذر الربط %s.%s <- %s", *m)
    return applied

