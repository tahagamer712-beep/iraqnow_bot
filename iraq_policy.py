def bump(key, n=1):
    if key in _STATS:
        _STATS[key] += n


def stats_line_and_reset():
    parts = [(k, v) for k, v in _STATS.items() if v]
    for k in _STATS:
        _STATS[k] = 0
    if not parts:
        return None
    labels = {"world_minor_held": "عالمي روتيني محجوب", "world_major_held_lowimp": "عالمي كبير منخفض الأهمية محجوب", "regional_held": "إقليمي محجوب (عراقي فقط)", "world_major_held": "عالمي كبير محجوب (عراقي فقط)", "gaza_blocked": "غزة محظور (أمر طه)"}
