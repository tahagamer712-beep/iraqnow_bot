# أوزان قابلة للضبط لاحقًا من لوحة الإدارة (مرحلة 7/8)
WEIGHTS = {"iraq_hit": 3, "entity_hit": 4, "regional_hit": 2, "world_major_hit": 2}


def _hits(text, words):
    t = text or ""
    return [w for w in words if w and w in t]


def classify_news(title, summary=""):
    """يعيد (الصنف, الدرجة, أسباب) — الصنف: iraq|regional|world_major|world_minor|blocked_topic."""
    text = f"{title or ''} {summary or ''}"
    # الحظر المطلق أولًا — قبل أي نقاط عراقية/إقليمية (أمر طه 2026-10-22)
    blocked_hits = _hits(text, BLOCKED_TOPICS)
    if blocked_hits:
        return "blocked_topic", 0, ["موضوع محظور بأمر طه: " + "، ".join(blocked_hits[:3])]
    iraq_hits = _hits(text, IRAQ_PLACES)
    ent_hits = _hits(text, IRAQ_ENTITIES)
    # FIX 2026-10-22: حارس «السوداني» — اسم رئيس الوزراء العراقي (محمد شياع
    # السوداني) لكنه أيضًا نسبة دولة السودان؛ بلا قرينة «شياع» كان كل خبر عن
    # الجيش/الحكومة السودانية يُصنَّف عراقيًا. يُحسب فقط مع «شياع».
    if "شياع" not in text:
        ent_hits = [h for h in ent_hits if h not in ("السوداني", "sudani")]
    reg_hits = _hits(text, REGIONAL_IMPACT)
    wm_hits = _hits(text, WORLD_MAJOR)
    score = (len(iraq_hits) * WEIGHTS["iraq_hit"] + len(ent_hits) * WEIGHTS["entity_hit"]
             + len(reg_hits) * WEIGHTS["regional_hit"] + len(wm_hits) * WEIGHTS["world_major_hit"])
    reasons = []
    if iraq_hits:
        reasons.append("مكان عراقي: " + "، ".join(iraq_hits[:3]))
    if ent_hits:
        reasons.append("جهة عراقية: " + "، ".join(ent_hits[:3]))
    if iraq_hits or ent_hits:
        return "iraq", score, reasons
    if reg_hits:
        reasons.append("أثر إقليمي: " + "، ".join(reg_hits[:3]))
        return "regional", score, reasons
    if wm_hits:
        reasons.append("حدث عالمي كبير: " + "، ".join(wm_hits[:3]))
        return "world_major", score, reasons
    return "world_minor", score, ["لا صلة بالعراق ولا حدث عالمي استثنائي"]


def publishable(cls, importance=0):
    """بوابة النشر التلقائي: العراقي والإقليمي يمران؛ العالمي الكبير يحتاج
    أهمية (درجة أهمية العنوان ≥1 أو كلمة حدث كبير)؛ العالمي الروتيني يُحجب."""
    if cls in ("iraq", "regional"):
        return True
    if cls == "world_major":
        return importance >= 1
    return False


